const assert = require('node:assert/strict');
const L = require('./ui/core.js');
let state = L.initial();
const first = state.accounts[0].id;
const second = state.accounts[1].id;
state.accounts[0].balance = 10000;
state.accounts[1].balance = 5000;
assert.equal(L.cents('0.29'),29);
assert.equal(L.cents('100.01'),10001);
for(const bad of ['-1','1.111','1e2','NaN','']) assert.throws(()=>L.cents(bad));
const input = {amount:1299,kind:'expense',accountId:first,date:'2026-10-12',category:'餐饮',note:'午餐'};
let next = L.saveEntry(state,input);
assert.equal(state.accounts[0].balance,10000,'原始状态不能被修改');
assert.equal(next.accounts[0].balance,8701);
assert.deepEqual(L.totals(next,'2026-10-12'),{expense:1299,income:0,count:1});
const entryId = next.entries[0].id;
next = L.saveEntry(next,{...input,amount:2000,accountId:second},entryId);
assert.equal(next.accounts[0].balance,10000,'换账户编辑需要恢复原账户');
assert.equal(next.accounts[1].balance,3000);
assert.equal(next.entries.length,1,'编辑不增加记录');
next = L.saveEntry(next,{...input,amount:1000,kind:'income',accountId:second},entryId);
assert.equal(next.accounts[1].balance,6000,'支出改收入需要撤销原支出');
next = L.removeEntry(next,entryId);
assert.equal(next.accounts[1].balance,5000,'删除收入恢复余额');
assert.equal(next.entries.length,0);
assert.throws(()=>L.saveEntry(state,{...input,amount:0}));
assert.throws(()=>L.saveEntry(state,{...input,date:'2026-02-30'}));
assert.throws(()=>L.saveEntry(state,{...input,accountId:'missing'}));
assert.equal(L.validDate('2024-02-29'),true);
assert.equal(L.validDate('2026-02-29'),false);
assert.throws(()=>L.validate({...state,accounts:[state.accounts[0],state.accounts[0]]}));
assert.throws(()=>L.validate({...state,entries:[{...input,id:'bad',accountId:'missing'}]}));
assert.deepEqual(L.validate(JSON.parse(JSON.stringify(state))),state,'备份恢复保持完整数据');
console.log('全部通过：金额精度、记账扣款、跨账户编辑、收支切换、删除恢复、日期校验、备份校验。');
