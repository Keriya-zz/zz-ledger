const assert = require('node:assert/strict');
const L = require('../ui/core.js');
let state = L.initial();
const [a,b,c] = state.accounts;
const entry = {kind:'expense',amount:10,date:'2026-10-01',category:'其他',note:'',accountId:a.id};
state = L.saveEntry(state,entry);
state = L.saveEntry(state,{...entry,amount:20,date:'2026-10-31'});
state = L.saveEntry(state,{...entry,accountId:b.id,amount:70,category:'还款'});
state = L.saveEntry(state,{...entry,amount:900,kind:'income'});
state = L.saveEntry(state,{...entry,amount:800,date:'2026-09-30'});
state = L.saveEntry(state,{...entry,amount:800,date:'2026-11-01'});
const original = JSON.stringify(state);
let rows = L.accountExpenses(state,'2026-10');
assert.deepEqual(rows.map(r=>[r.id,r.amount,r.count,r.share]),[[b.id,70,1,70],[a.id,30,2,30],[c.id,0,0,0]]);
assert.equal(JSON.stringify(state),original);
assert.ok(L.accountExpenses(state,'2026-12').every(r=>r.amount===0 && r.count===0 && r.share===0));
assert.deepEqual(L.accountExpenses({accounts:[],entries:[]},'2026-10'),[]);
const id=state.entries.find(e=>e.accountId===b.id).id;
state=L.saveEntry(state,{...entry,accountId:c.id,amount:50},id);
rows=L.accountExpenses(state,'2026-10');
assert.equal(rows.find(r=>r.id===b.id).amount,0);
assert.equal(rows.find(r=>r.id===c.id).amount,50);
state=L.removeEntry(state,id);
assert.equal(L.accountExpenses(state,'2026-10').find(r=>r.id===c.id).count,0);
console.log('PASS: 账户支出按月汇总、分单位精度、收入排除、还款计入、零支出、跨账户编辑和删除同步。');
