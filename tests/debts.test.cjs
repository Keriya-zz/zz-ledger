const assert = require('node:assert/strict');
const L = require('../ui/core.js');
let state=L.initial(); const a=state.accounts[0].id, b=state.accounts[1].id;
state.accounts[0].balance=100000; state.accounts[1].balance=50000;
delete state.debts; L.validate(state);
state=L.saveDebt(state,{name:'信用卡',creditor:'银行',amount:60000,dueDate:'2026-10-20',note:''});
const debtId=state.debts[0].id;
assert.equal(state.accounts[0].balance,100000,'登记待还款不扣账户');
state=L.repayDebt(state,debtId,{amount:20000,accountId:a,date:'2026-10-12',note:''});
const entryId=state.entries[0].id;
assert.equal(state.accounts[0].balance,80000);
assert.equal(L.debtDetails(state)[0].remaining,40000);
assert.equal(state.entries[0].category,'还款');
assert.equal(L.totals(state,'2026-10-12').expense,20000);
assert.throws(()=>L.repayDebt(state,debtId,{amount:40001,accountId:a,date:'2026-10-12',note:''}));
assert.throws(()=>L.saveDebt(state,{...state.debts[0],amount:19999},debtId));
assert.throws(()=>L.removeDebt(state,debtId));
state=L.saveEntry(state,{amount:10000,kind:'expense',category:'还款',accountId:b,date:'2026-10-13',note:'编辑'},entryId);
assert.equal(state.accounts[0].balance,100000);
assert.equal(state.accounts[1].balance,40000);
assert.equal(state.entries[0].debtId,debtId,'编辑保留关联');
assert.equal(L.debtDetails(state)[0].remaining,50000);
assert.throws(()=>L.saveEntry(state,{amount:10000,kind:'income',category:'还款',accountId:b,date:'2026-10-13',note:''},entryId));
state=L.repayDebt(state,debtId,{amount:50000,accountId:a,date:'2026-10-14',note:''});
assert.equal(L.debtDetails(state)[0].remaining,0);
assert.throws(()=>L.repayDebt(state,debtId,{amount:1,accountId:a,date:'2026-10-14',note:''}));
state=L.removeEntry(state,state.entries[0].id);
assert.equal(state.accounts[0].balance,100000);
assert.equal(L.debtDetails(state)[0].remaining,50000,'撤销还款恢复待还金额');
state=L.removeEntry(state,entryId); state=L.removeDebt(state,debtId);
assert.equal(state.debts.length,0); assert.equal(state.accounts[1].balance,50000);
for (const dueDate of ['2026-02-30',null,undefined]) assert.throws(()=>L.saveDebt(state,{name:'测试',creditor:'',amount:100,dueDate,note:''}));
state=L.saveDebt(state,{name:'未设日期',creditor:'',amount:100,dueDate:'',note:''});
assert.deepEqual(L.validate(JSON.parse(JSON.stringify(state))),state);
console.log('PASS: 旧账本兼容、部分/全额还款、跨账户编辑、撤销恢复、超额保护和备份兼容。');
